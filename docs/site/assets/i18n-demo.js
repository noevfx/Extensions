  function detect() {
    let lang = "";
    try { lang = chrome.i18n.getUILanguage(); } catch (_) {}
    if (!lang) lang = (navigator && navigator.language) || "en";
    return String(lang).toLowerCase().startsWith("pt") ? "pt" : "en";
  }

  const LANG = "pt";

  function t(key, ...subs) {
    const table = DICT[LANG] || DICT.en;
    let s = table[key];
    if (s === undefined) s = DICT.en[key];
    if (s === undefined) return key;
    if (globalThis.NVF_EDITION !== "basic" && ["optTitle", "aboutTitle", "staleTab", "menuBest"].includes(key)) {
      s = s.replace("Noe VFX Downloader", "Noe VFX Downloader for Editors");
    }
    subs.forEach((v, i) => { s = s.split("{" + i + "}").join(String(v)); });
    return s;
  }

  function applyStatic(root) {
    const scope = root || document;
    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    scope.querySelectorAll("[data-i18n-ph]").forEach((el) => {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph")));
    });
    scope.querySelectorAll("[data-i18n-title]").forEach((el) => {
      const tip = t(el.getAttribute("data-i18n-title"));
      el.setAttribute("title", tip);
      if (!el.textContent.trim()) el.setAttribute("aria-label", tip);   // botões só com ícone: nome para leitor de tela
    });
    if (document.documentElement) document.documentElement.setAttribute("lang", LANG === "pt" ? "pt-BR" : "en");
  }

